# Variables, types and what they are.
# You can check a variable's type with -> type(variable)

# String - Text data
first_name = "Patricia"
last_name = "Oliveira"

# Integer - Whole numbers 1 - 2 - 120
age = 25

# Float - Decimal numbers 1.5 - 12.5
height = 1.6

# Boolean - True/False values
is_student = True

# List - Ordered, changeable collection (allows duplicates)
fruits = ["apple", "banana", "orange"]

# Tuple - Ordered, unchangeable collection
coordinates = (10, 20)

# Dictionary - Key-value pairs
person = {"name": "Patricia", "age": 35, "country": "Brazil"}

# Set - Unordered collection of unique items
unique_numbers = {1, 2, 3, 4, 5}

# None - Represents absence of value
result = None

# Complex (complex number) - Numbers with real and imaginary parts
complex_num = 3 + 4j

print(f"Hello {first_name} {last_name}, you are {age} years old")
print(type(first_name))
